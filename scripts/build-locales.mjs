import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { questions as legacy } from "../src/legacy-questions.js";
import { bank } from "../src/bank.js";
import { normalize } from "../src/answers.js";
import { locales } from "../public/locales.js";

const questions = [...legacy, ...bank];
const translations = Object.fromEntries(questions.map((question) => [question.id, {
  sourcePrompt: question.prompt,
  sourceAnswers: question.answers.map((answer) => answer.label),
  languages: {},
}]));
const messages = {};
const collisions = [];
const sourceMessages = JSON.parse(await readFile("content/translations/messages.en.json", "utf8"));
const overrides = JSON.parse(await readFile("content/translations/overrides.json", "utf8"));
const placeholders = (value) => (value.match(/\{\d+\}/g) || []).sort().join(",");
for (const { code } of locales.filter((locale) => locale.code !== "en")) {
  for (const key of Object.keys(overrides.messages?.[code] || {})) {
    if (!(key in sourceMessages)) throw new Error(`Unknown ${code} message override: ${key}`);
  }
  for (const id of Object.keys(overrides.questions?.[code] || {})) {
    if (!translations[id]) throw new Error(`Unknown ${code} question override: ${id}`);
  }
  const content = JSON.parse(await readFile(`content/translations/${code}.json`, "utf8"));
  const catalog = {
    ...JSON.parse(await readFile(`content/translations/messages.${code}.json`, "utf8")),
    ...overrides.messages?.[code],
  };
  messages[code] = Object.fromEntries(Object.keys(sourceMessages).map((key) => [key, catalog[key]]));
  for (const key of Object.keys(sourceMessages)) {
    const value = messages[code][key];
    if (typeof value !== "string" || !value.trim() || placeholders(key) !== placeholders(value)) {
      throw new Error(`Incomplete ${code} interface message: ${key}`);
    }
    const protectedTerms = [
      ...["RARE Air", "Krillion"].filter((term) => key.includes(term)),
      ...(key.match(/[\w.+-]+@[\w.-]+\.[a-z]{2,}/gi) || []),
    ];
    for (const term of protectedTerms) {
      if (!value.includes(term)) throw new Error(`Changed protected term in ${code} message: ${term}`);
    }
  }
  for (const question of questions) {
    const entry = content.questions[question.id];
    const source = JSON.stringify([question.prompt, question.answers.map((answer) => answer.label)]);
    const fingerprint = createHash("sha256").update(source).digest("hex");
    if (!entry || entry.sourceHash !== fingerprint || !entry.prompt?.trim() ||
        entry.answers?.length !== question.answers.length || entry.answers.some((answer) => !answer?.trim())) {
      throw new Error(`Incomplete or outdated ${code} translation for ${question.id}`);
    }
    const override = overrides.questions?.[code]?.[question.id] || {};
    const prompt = override.prompt || entry.prompt;
    for (const year of question.prompt.match(/\b(?:1\d{3}|20\d{2})\b/g) || []) {
      if (!normalize(prompt).includes(year)) throw new Error(`Missing source year ${year} in ${code} ${question.id}`);
    }
    for (const label of [...Object.keys(override.answers || {}), ...Object.keys(override.aliases || {})]) {
      if (!question.answers.some((answer) => answer.label === label)) {
        throw new Error(`Unknown canonical answer in ${code} override for ${question.id}: ${label}`);
      }
    }
    translations[question.id].languages[code] = {
      prompt,
      answers: question.answers.map((answer, index) => override.answers?.[answer.label] || entry.answers[index]),
      aliases: question.answers.map((answer) => override.aliases?.[answer.label] || []),
    };
  }
}
for (const question of questions) {
  for (const [code, entry] of Object.entries(translations[question.id].languages)) {
    // Local words can overlap an English abbreviation with a different meaning
    // (German Grad = degree; English grad = gradian). Canonical names stay safe.
    const known = new Map(question.answers.map((answer, index) => [normalize(answer.label), index]));
    entry.answers.forEach((label, index) => {
      for (const value of [label, ...entry.aliases[index]]) {
        const key = normalize(value);
        if (value.length > 100) throw new Error(`Localized answer exceeds the input limit: ${code} ${question.id} ${value}`);
        if (!key) throw new Error(`Empty normalized answer in ${code} ${question.id}`);
        if (known.has(key) && known.get(key) !== index) {
          collisions.push(`${question.id} ${code} ${JSON.stringify(value)} conflicts with ${question.answers[known.get(key)].label}`);
        } else known.set(key, index);
      }
    });
  }
}
if (collisions.length) throw new Error("Translated answer aliases conflict\n" + collisions.join("\n"));
await writeFile("src/localized-bank.js", "// Generated by npm run locale:build. Server-only question translations.\nexport const translations = " + JSON.stringify(translations) + ";\n");
await writeFile("public/translations.js", "// Generated by npm run locale:build. Interface and guide messages.\nexport const messages = " + JSON.stringify(messages) + ";\n");
console.log(`Validated ${questions.length} questions in ${locales.length} languages and their answer aliases.`);
